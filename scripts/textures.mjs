// =====================================================================
// Texture pipeline
//
//   node scripts/textures.mjs build     compile textures/*.texture
//   node scripts/textures.mjs list      show every texture and its size
//   node scripts/textures.mjs import <png> --into <file.texture> --name <n>
//   node scripts/textures.mjs export [<fam>:<name>] [--out dir]
//
// build.mjs runs `build` automatically, so `npm run build` always ships
// textures that match the .texture files on disk.
// =====================================================================
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, existsSync, copyFileSync } from 'node:fs';
import { resolve, dirname, join, relative, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { decodePng, encodePng } from './png.mjs';

const require = createRequire(import.meta.url);
const TEX = require('../js/texture.js');

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const TEXTURE_DIR = resolve(ROOT, 'textures');
const OUT_FILE = resolve(ROOT, 'js/textures.generated.js');

function walk(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

function textureFiles() {
  return walk(TEXTURE_DIR).filter(p => p.endsWith('.texture')).sort();
}

// Recursively resolve { "op": "png", "src": ... } into an embedded RGBA ref.
function resolveImages(ops, images, file) {
  for (const op of ops) {
    if (!op || typeof op !== 'object') continue;
    if (op.op === 'png' && op.src) {
      const src = op.src;
      let key = src, buf;
      if (src.startsWith('data:')) {
        key = file + ':' + (op.name || 'inline') + ':' + src.length + ':' + src.slice(-24);
        buf = Buffer.from(src.slice(src.indexOf(',') + 1), 'base64');
      } else {
        // sprite paths are relative to textures/ (import writes there), with the
        // project root as a fallback for paths that spell out "textures/..."
        const abs = [resolve(TEXTURE_DIR, src), resolve(ROOT, src)].find(existsSync);
        if (!abs) throw new Error(file + ': missing sprite "' + src + '" (looked in textures/ and the project root)');
        buf = readFileSync(abs);
        key = src.replace(/\\/g, '/');
      }
      const img = images[key] || decodePng(buf);
      images[key] = img;
      delete op.src;
      op.ref = key;
    }
    if (op.ops) resolveImages(op.ops, images, file);
    if (op.then) resolveImages(op.then, images, file);
    if (op.else) resolveImages(op.else, images, file);
  }
}

export function buildTextures(root = ROOT, outFile = OUT_FILE) {
  const files = {};
  const images = Object.create(null);
  const problems = [];

  for (const path of textureFiles()) {
    const rel = relative(resolve(root, 'textures'), path).replace(/\\/g, '/');
    const key = rel.replace(/\.texture$/, '');
    let doc;
    try {
      doc = TEX.parse(readFileSync(path, 'utf8'));
    } catch (err) {
      problems.push(rel + ': not valid JSONC — ' + err.message);
      continue;
    }
    if (doc.name && doc.name !== key) problems.push(rel + ': "name" is "' + doc.name + '" but the file is "' + key + '"');
    doc.name = key;
    for (const name of Object.keys(doc.textures || {})) {
      try {
        resolveImages(doc.textures[name].ops || [], images, key);
      } catch (err) {
        problems.push(rel + ':' + name + ': ' + err.message);
      }
    }
    files[key] = doc;
  }

  problems.push(...TEX.validate(files));
  if (problems.length) {
    throw new Error('texture build failed:\n  ' + problems.join('\n  '));
  }

  const imageOut = {};
  for (const k of Object.keys(images).sort()) {
    const img = images[k];
    imageOut[k] = { w: img.width, h: img.height, b64: Buffer.from(img.data.buffer, img.data.byteOffset, img.data.length).toString('base64') };
  }
  const body = [
    '// GENERATED by scripts/textures.mjs — do not edit.',
    '// Source: textures/*.texture. Run `npm run textures` after changing them.',
    'TEX.defineImages(' + JSON.stringify(imageOut) + ');',
    'TEX.define(' + JSON.stringify(files) + ');',
    '',
  ].join('\n');
  writeFileSync(outFile, body, 'utf8');
  const count = Object.values(files).reduce((n, d) => n + Object.keys(d.textures || {}).length, 0);
  return { files: Object.keys(files).length, textures: count, images: Object.keys(imageOut).length, outFile };
}

// ---------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------
function familyPath(family) {
  const p = resolve(TEXTURE_DIR, family + '.texture');
  if (!existsSync(p)) throw new Error('no such texture family: ' + family);
  return p;
}

function cmdList() {
  const files = {};
  for (const path of textureFiles()) {
    const key = relative(TEXTURE_DIR, path).replace(/\\/g, '/').replace(/\.texture$/, '');
    files[key] = TEX.parse(readFileSync(path, 'utf8'));
  }
  TEX.define(files);
  for (const fam of Object.keys(files).sort()) {
    console.log(fam + '.texture');
    for (const name of Object.keys(files[fam].textures).sort()) {
      const t = files[fam].textures[name];
      const size = t.size ? t.size[0] + 'x' + t.size[1] : 'inherited';
      console.log('  ' + name.padEnd(22) + size);
    }
  }
}

function cmdImport(args) {
  const src = args[0];
  const opt = (flag, dflt) => {
    const i = args.indexOf(flag);
    return i >= 0 ? args[i + 1] : dflt;
  };
  if (!src || !opt('--into') || !opt('--name')) throw new Error('usage: import <png> --into <family> --name <name> [--at x,y]');
  const family = opt('--into').replace(/\.texture$/, '');
  const name = opt('--name');
  const file = familyPath(family);
  const img = decodePng(readFileSync(resolve(process.cwd(), src)));
  const at = (opt('--at', '0,0')).split(',').map(Number);

  mkdirSync(resolve(TEXTURE_DIR, 'sprites'), { recursive: true });
  let sprite = resolve(TEXTURE_DIR, 'sprites', basename(src));
  if (resolve(process.cwd(), src) !== sprite) copyFileSync(resolve(process.cwd(), src), sprite);
  const ref = 'sprites/' + basename(src);

  const text = readFileSync(file, 'utf8');
  if (new RegExp('"' + name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '"\\s*:').test(text)) {
    throw new Error(family + ': texture "' + name + '" already exists');
  }
  const entry = {
    size: [img.width, img.height],
    params: {},
    ops: [{ op: 'png', src: ref, x: at[0], y: at[1] }],
  };
  const snippet = '\n    ' + JSON.stringify(name) + ': ' + JSON.stringify(entry, null, 2).replace(/\n/g, '\n    ') + ',';
  const anchor = text.indexOf('"textures"');
  const brace = text.indexOf('{', anchor);
  if (anchor < 0 || brace < 0) throw new Error(family + ': no "textures" object');
  writeFileSync(file, text.slice(0, brace + 1) + snippet + text.slice(brace + 1), 'utf8');
  console.log('imported ' + name + ' (' + img.width + 'x' + img.height + ') into ' + family + '.texture as ' + ref);
}

function cmdExport(args) {
  const only = args.find(a => !a.startsWith('--') && args[args.indexOf(a) - 1] !== '--out');
  const outIdx = args.indexOf('--out');
  const outDir = resolve(ROOT, outIdx >= 0 ? args[outIdx + 1] : 'textures/export');
  mkdirSync(outDir, { recursive: true });

  const files = {};
  for (const path of textureFiles()) {
    const key = relative(TEXTURE_DIR, path).replace(/\\/g, '/').replace(/\.texture$/, '');
    files[key] = TEX.parse(readFileSync(path, 'utf8'));
  }
  TEX.define(files);
  let fam = null, tex = null;
  if (only) {
    if (only.includes(':')) [fam, tex] = only.split(':');
    else if (files[only]) fam = only;
    else tex = only;
  }
  let n = 0;
  for (const family of Object.keys(files).sort()) {
    if (fam && family !== fam) continue;
    for (const name of Object.keys(files[family].textures).sort()) {
      if (tex && name !== tex) continue;
      const def = files[family].textures[name];
      if (def.extends && !def.ops) continue; // inherited art uses the parent's geometry
      const img = TEX.renderBuffer(family, name, {});
      const out = join(outDir, family + '__' + name + '.png');
      writeFileSync(out, encodePng({ width: img.w, height: img.h, data: img.data }));
      console.log('wrote ' + relative(ROOT, out) + '  ' + img.w + 'x' + img.h);
      n++;
    }
  }
  if (!n) throw new Error('nothing to export');
}

// Turn one or more PNGs into a self-contained .texture family. Each image
// is embedded as a data URI, so the finished file needs no other assets.
function cmdPack(args) {
  const flags = new Map();
  const inputs = [];
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a === '--out' || a === '--tile') { flags.set(a, args[++i]); }
    else if (a === '--link' || a === '--force') { flags.set(a, true); }
    else if (a.startsWith('--')) throw new Error('unknown flag ' + a);
    else inputs.push(a);
  }
  const outArg = flags.get('--out');
  if (!inputs.length || !outArg) {
    throw new Error('usage: pack <png|dir>... --out <textures/family.texture> [--link] [--tile 9] [--force]');
  }

  const outPath = resolve(process.cwd(), outArg);
  const family = basename(outPath).replace(/\.texture$/, '');
  if (!/^[a-z0-9_]+$/.test(family)) throw new Error('family name must be lower_snake_case: ' + family);
  if (existsSync(outPath) && !flags.get('--force')) {
    throw new Error(relative(ROOT, outPath) + ' already exists (use --force to replace it)');
  }
  const tile = Number(flags.get('--tile') || 9);
  const link = !!flags.get('--link');

  const files = [];
  for (const input of inputs) {
    const abs = resolve(process.cwd(), input);
    if (!existsSync(abs)) throw new Error('no such file or directory: ' + input);
    if (statSync(abs).isDirectory()) files.push(...walk(abs).filter(p => /\.png$/i.test(p)).sort());
    else files.push(abs);
  }
  if (!files.length) throw new Error('no PNG files found');

  const textures = {};
  for (const file of files) {
    const img = decodePng(readFileSync(file)); // also validates the PNG
    let name = basename(file).replace(/\.png$/i, '').toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^_+|_+$/g, '') || 'sprite';
    if (textures[name]) { let k = 2; while (textures[name + '_' + k]) k++; name += '_' + k; }

    let src;
    if (link) {
      mkdirSync(resolve(TEXTURE_DIR, 'sprites'), { recursive: true });
      const dest = resolve(TEXTURE_DIR, 'sprites', basename(file));
      if (resolve(file) !== dest) copyFileSync(file, dest);
      src = 'sprites/' + basename(file);
    } else {
      src = 'data:image/png;base64,' + readFileSync(file).toString('base64');
    }
    textures[name] = {
      size: [img.width, img.height],
      params: {},
      ops: [{ op: 'png', src, x: 0, y: 0 }],
    };
  }

  const doc = { format: TEX.FORMAT, name: family, tile, textures };
  const errs = TEX.validate({ [family]: doc });
  if (errs.length) throw new Error('packed file would not validate:\n  ' + errs.join('\n  '));

  const header = [
    '// Packed by scripts/textures.mjs pack on ' + new Date().toISOString().slice(0, 10) + '.',
    '// ' + Object.keys(textures).length + ' sprite(s). ' + (link ? 'Sprites live in textures/sprites/.' : 'Images are embedded as data URIs, so this file is self-contained.'),
    '// Edit a sprite by exporting it, editing the PNG, then packing again with --force.',
    '',
  ].join('\n');
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, header + JSON.stringify(doc, null, 2) + '\n', 'utf8');
  console.log('packed ' + Object.keys(textures).length + ' sprite(s) into ' + relative(ROOT, outPath));
  for (const name of Object.keys(textures)) console.log('  ' + name.padEnd(22) + textures[name].size.join('x'));
  console.log('run `npm run textures` (or `npm run build`) to compile it');
}

function main(argv) {
  const [cmd, ...args] = argv;
  if (cmd === 'build') {
    const r = buildTextures();
    console.log(`textures: ${r.textures} in ${r.files} files, ${r.images} sprite(s) -> ${relative(ROOT, r.outFile)}`);
  } else if (cmd === 'list') cmdList();
  else if (cmd === 'import') cmdImport(args);
  else if (cmd === 'export') cmdExport(args);
  else if (cmd === 'pack') cmdPack(args);
  else {
    console.log('usage: textures.mjs <build|list|import|export|pack> [...]');
    process.exitCode = 1;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  try { main(process.argv.slice(2)); }
  catch (err) { console.error('textures: ' + err.message); process.exitCode = 1; }
}
