// =====================================================================
// Texture pipeline
//
//   node scripts/textures.mjs build     compile textures/*.texture
//   node scripts/textures.mjs list      show every texture and its size
//   node scripts/textures.mjs import <png> --into <file.texture> --name <n>
//   node scripts/textures.mjs export [<fam>:<name>] [--out dir]
//   node scripts/textures.mjs pack <png>... --out <textures/family.texture>
//
// build.mjs runs `build` automatically, so `npm run build` always ships
// textures that match the .texture files on disk.
// =====================================================================
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, existsSync } from 'node:fs';
import { resolve, dirname, join, relative, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { decodePng, encodePng } from './png.mjs';

const require = createRequire(import.meta.url);
const TEX = require('../js/texture.js');

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const TEXTURE_DIR = resolve(ROOT, 'textures');
const OUT_FILE = resolve(ROOT, 'js/textures.generated.js');

function walk(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

function textureFiles() {
  return walk(TEXTURE_DIR).filter(p => p.endsWith('.texture')).sort();
}

// One PNG becomes one design. Colours are de-duplicated into a palette, and
// transparent pixels become ".", so the result is ordinary pixel art.
export function imageToDesign(img) {
  const { width: w, height: h, data } = img;
  const palette = ['transparent'];
  const chars = new Map();
  const rows = [];
  for (let y = 0; y < h; y++) {
    let row = '';
    for (let x = 0; x < w; x++) {
      const o = (y * w + x) * 4;
      const a = data[o + 3];
      if (a === 0) { row += '.'; continue; }
      const key = [data[o], data[o + 1], data[o + 2], a].join(',');
      let ch = chars.get(key);
      if (!ch) {
        if (palette.length >= TEX.ALPHABET.length) {
          throw new Error('image has more than ' + (TEX.ALPHABET.length - 1) + ' colours; reduce its palette first');
        }
        palette.push('#' + [data[o], data[o + 1], data[o + 2]].map(v => v.toString(16).padStart(2, '0')).join('') +
          (a === 255 ? '' : a.toString(16).padStart(2, '0')));
        ch = TEX.ALPHABET[palette.length - 1];
        chars.set(key, ch);
      }
      row += ch;
    }
    rows.push(row);
  }
  return { palette, rows };
}

export function buildTextures(root = ROOT, outFile = OUT_FILE) {
  const files = {};
  const problems = [];

  for (const path of textureFiles()) {
    const rel = relative(resolve(root, 'textures'), path).replace(/\\/g, '/');
    const key = rel.replace(/\.texture$/, '');
    let doc;
    try {
      doc = TEX.parse(readFileSync(path, 'utf8'));
    } catch (err) {
      problems.push(rel + ': not valid JSONC — ' + err.message);
      continue;
    }
    if (doc.name && doc.name !== key) problems.push(rel + ': "name" is "' + doc.name + '" but the file is "' + key + '"');
    doc.name = key;
    files[key] = doc;
  }

  problems.push(...TEX.validate(files));
  if (problems.length) {
    throw new Error('texture build failed:\n  ' + problems.join('\n  '));
  }

  const body = [
    '// GENERATED by scripts/textures.mjs — do not edit.',
    '// Source: textures/*.texture. Run `npm run textures` after changing them.',
    'TEX.define(' + JSON.stringify(files) + ');',
    '',
  ].join('\n');
  writeFileSync(outFile, body, 'utf8');
  const count = Object.values(files).reduce((n, d) => n + Object.keys(d.textures || {}).length, 0);
  return { files: Object.keys(files).length, textures: count, outFile };
}

function writeFamily(path, doc) {
  const header = [
    '// texture/2 — designs of pixel rows, conditions in short text.',
    '// A condition chooses the design to paint, e.g. "m = 5" or "hw > 0 and night".',
    '// Edit with the Texture Studio (npm run build, then /textures).',
    '',
  ].join('\n');
  writeFileSync(path, header + TEX.stringify(doc) + '\n', 'utf8');
}

// ---------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------
function familyPath(family) {
  const p = resolve(TEXTURE_DIR, family + '.texture');
  if (!existsSync(p)) throw new Error('no such texture family: ' + family);
  return p;
}

function cmdList() {
  const files = {};
  for (const path of textureFiles()) {
    const key = relative(TEXTURE_DIR, path).replace(/\\/g, '/').replace(/\.texture$/, '');
    files[key] = TEX.parse(readFileSync(path, 'utf8'));
  }
  TEX.define(files);
  for (const fam of Object.keys(files).sort()) {
    console.log(fam + '.texture');
    for (const name of Object.keys(files[fam].textures).sort()) {
      const t = files[fam].textures[name];
      const size = t.size ? t.size[0] + 'x' + t.size[1] : '?';
      console.log('  ' + name.padEnd(22) + size.padEnd(8) + Object.keys(t.designs || {}).length + ' design(s)');
    }
  }
}

function cmdImport(args) {
  const src = args[0];
  const opt = (flag, dflt) => {
    const i = args.indexOf(flag);
    return i >= 0 ? args[i + 1] : dflt;
  };
  if (!src || !opt('--into') || !opt('--name')) throw new Error('usage: import <png> --into <family> --name <name>');
  const family = opt('--into').replace(/\.texture$/, '');
  const name = opt('--name');
  const file = familyPath(family);
  const img = decodePng(readFileSync(resolve(process.cwd(), src)));
  const doc = TEX.parse(readFileSync(file, 'utf8'));
  if (doc.textures[name]) throw new Error(family + ': texture "' + name + '" already exists');
  const design = imageToDesign(img);
  doc.textures[name] = {
    size: [img.width, img.height],
    params: {},
    designs: { base: design },
  };
  writeFamily(file, doc);
  console.log('imported ' + name + ' (' + img.width + 'x' + img.height + ') into ' + family + '.texture');
}

function cmdExport(args) {
  const only = args.find(a => !a.startsWith('--') && args[args.indexOf(a) - 1] !== '--out');
  const outIdx = args.indexOf('--out');
  const outDir = resolve(ROOT, outIdx >= 0 ? args[outIdx + 1] : 'textures/export');
  mkdirSync(outDir, { recursive: true });

  const files = {};
  for (const path of textureFiles()) {
    const key = relative(TEXTURE_DIR, path).replace(/\\/g, '/').replace(/\.texture$/, '');
    files[key] = TEX.parse(readFileSync(path, 'utf8'));
  }
  TEX.define(files);
  let fam = null, tex = null;
  if (only) {
    if (only.includes(':')) [fam, tex] = only.split(':');
    else if (files[only]) fam = only;
    else tex = only;
  }
  let n = 0;
  for (const family of Object.keys(files).sort()) {
    if (fam && family !== fam) continue;
    for (const name of Object.keys(files[family].textures).sort()) {
      if (tex && name !== tex) continue;
      const img = TEX.renderBuffer(family, name, {});
      const out = join(outDir, family + '__' + name + '.png');
      writeFileSync(out, encodePng({ width: img.w, height: img.h, data: img.data }));
      console.log('wrote ' + relative(ROOT, out) + '  ' + img.w + 'x' + img.h + '  design ' + img.marks.design);
      n++;
    }
  }
  if (!n) throw new Error('nothing to export');
}

// Turn one or more PNGs into a family of pixel designs.
function cmdPack(args) {
  const flags = new Map();
  const inputs = [];
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a === '--out' || a === '--tile') { flags.set(a, args[++i]); }
    else if (a === '--force') { flags.set(a, true); }
    else if (a.startsWith('--')) throw new Error('unknown flag ' + a);
    else inputs.push(a);
  }
  const outArg = flags.get('--out');
  if (!inputs.length || !outArg) {
    throw new Error('usage: pack <png|dir>... --out <textures/family.texture> [--tile 9] [--force]');
  }

  const outPath = resolve(process.cwd(), outArg);
  const family = basename(outPath).replace(/\.texture$/, '');
  if (!/^[a-z0-9_]+$/.test(family)) throw new Error('family name must be lower_snake_case: ' + family);
  if (existsSync(outPath) && !flags.get('--force')) {
    throw new Error(relative(ROOT, outPath) + ' already exists (use --force to replace it)');
  }
  const tile = Number(flags.get('--tile') || 9);

  const files = [];
  for (const input of inputs) {
    const abs = resolve(process.cwd(), input);
    if (!existsSync(abs)) throw new Error('no such file or directory: ' + input);
    if (statSync(abs).isDirectory()) files.push(...walk(abs).filter(p => /\.png$/i.test(p)).sort());
    else files.push(abs);
  }
  if (!files.length) throw new Error('no PNG files found');

  const textures = {};
  for (const file of files) {
    const img = decodePng(readFileSync(file));
    let name = basename(file).replace(/\.png$/i, '').toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^_+|_+$/g, '') || 'sprite';
    if (textures[name]) { let k = 2; while (textures[name + '_' + k]) k++; name += '_' + k; }
    textures[name] = {
      size: [img.width, img.height],
      params: {},
      designs: { base: imageToDesign(img) },
    };
  }

  const doc = { format: TEX.FORMAT, name: family, tile, textures };
  const errs = TEX.validate({ [family]: doc });
  if (errs.length) throw new Error('packed file would not validate:\n  ' + errs.join('\n  '));

  mkdirSync(dirname(outPath), { recursive: true });
  writeFamily(outPath, doc);
  console.log('packed ' + Object.keys(textures).length + ' sprite(s) into ' + relative(ROOT, outPath));
  for (const name of Object.keys(textures)) console.log('  ' + name.padEnd(22) + textures[name].size.join('x'));
  console.log('run `npm run textures` (or `npm run build`) to compile it');
}

function main(argv) {
  const [cmd, ...args] = argv;
  if (cmd === 'build') {
    const r = buildTextures();
    console.log(`textures: ${r.textures} in ${r.files} files -> ${relative(ROOT, r.outFile)}`);
  } else if (cmd === 'list') cmdList();
  else if (cmd === 'import') cmdImport(args);
  else if (cmd === 'export') cmdExport(args);
  else if (cmd === 'pack') cmdPack(args);
  else {
    console.log('usage: textures.mjs <build|list|import|export|pack> [...]');
    process.exitCode = 1;
  }
}

